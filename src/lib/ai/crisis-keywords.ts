/**
 * 위기 신호 1단 — 키워드. 순수·동기. 네트워크 없음.
 *
 * **재현율 우선이다.** 놓치는 것보다 넘치는 게 낫다 — 걸린 것은 2단(저가 모델)이
 * 다시 판단한다. 그래서 과거형("그땐 죽고 싶었지만")도 여기서는 통과시키지 않고
 * 2단으로 넘긴다. 반대로 **1단 단독으로는 절대 차단하지 않는다**(스펙 §9).
 *
 * 관용 표현("배고파 죽겠다")만 예외로 먼저 걸러낸다 — 이건 2단을 부를 가치도 없다.
 */

/**
 * "죽겠다"류 관용구. 이걸 지운 나머지에서 위기 어근을 다시 찾는다.
 *
 * 지우고 다시 보는 이유: "배고파 죽겠다"는 위기가 아니지만
 * "배고파 죽겠다. 진짜 죽고 싶어"는 위기다. 단순히 관용구가 있다고 통과시키면
 * 뒤에 붙은 진짜 신호를 놓친다.
 */
const IDIOM_PATTERNS: RegExp[] = [
  /(배고파|배고프|더워|덥어|추워|힘들어|웃겨|귀여워|좋아|피곤해|졸려|바빠|심심해)\s*죽\S*/g,
  /죽는\s*줄/g,
  /죽겠(다|어|네|군|음)/g,
];

/** 위기 신호 어근. 공백을 제거한 문자열에 대해 검사한다. */
const CRISIS_PATTERNS: RegExp[] = [
  // 자해·자살 직접
  /자살/,
  /자해/,
  /죽고싶/,
  /죽어버리/,
  /목숨을끊/,
  // 소멸 욕구·완곡어
  /사라지고싶/,
  /없어지고싶/,
  /태어나지말았/,
  /살기싫/,
  /살고싶지않/,
  // 작별·유서
  /유서/,
  /마지막인사/,
  /먼저갈게/,
];

/**
 * 위기 키워드가 있는가.
 *
 * 공백을 제거하고 검사한다 — "자 살", "죽고 싶다"처럼 띄어쓰기를 바꿔도 잡기 위해서다.
 */
export function hasCrisisKeyword(text: string): boolean {
  const raw = text.trim();
  if (!raw) return false;

  let residue = raw;
  for (const p of IDIOM_PATTERNS) residue = residue.replace(p, " ");

  const squashed = residue.replace(/\s+/g, "");
  return CRISIS_PATTERNS.some((p) => p.test(squashed));
}
